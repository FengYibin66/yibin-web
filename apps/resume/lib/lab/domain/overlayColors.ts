/**
 * Lab 覆盖层文案的颜色。
 *
 * 集中在这里、并由 `__tests__/labContrast.test.ts` 按 WCAG 断言，是因为
 * 审计 E10 那两处（"退出 Lab" 金色 0.6 alpha = 对比度 1.9、
 * "SCROLL TO EXPLORE" 墨色 0.4 alpha = 2.4）都是**内联样式里的一个数字**，
 * 改的时候凭手感调成"我这块屏上够了"就完了。
 *
 * Lab 的背景是走廊的纸白（墙、地、天花都在 #ece7dd..#f4f0e8 之间），
 * 所以这里以 `CORRIDOR_PAPER` 为基准算对比度。
 */

/** 走廊纸白 —— 覆盖层文案的实际背景（取最亮的那面墙，最坏情况） */
export const CORRIDOR_PAPER = '#f4f0e8'

export const OVERLAY_COLORS = {
  /**
   * 走廊底部的操作提示（"滚动" / "上下滑动"）。
   *
   * 原先是 `rgba(42,31,14,0.4)`，压到纸白上是 rgb(161,154,142)，
   * 对比度 2.4。这是小字（10px），按正文要求 4.5。
   */
  hint: 'rgba(42,31,14,0.72)',

  /**
   * "← 退出 Lab"。
   *
   * 原先是 `rgba(200,169,110,0.6)`——金色在纸白上本来就浅，再乘 0.6 之后
   * 对比度只有 1.9，实机上基本看不见。改成不透明的深金：保住"这是个金色的
   * 品牌口子"，同时过 4.5。
   */
  exitLab: '#7a5d20',
} as const
