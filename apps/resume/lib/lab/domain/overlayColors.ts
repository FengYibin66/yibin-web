/**
 * Lab 覆盖层文案的颜色。
 *
 * 集中在这里、并由 `__tests__/labContrast.test.ts` 按 WCAG 断言，是因为
 * 审计 E10 那两处（"退出 Lab" 金色 0.6 alpha = 对比度 1.9、
 * "SCROLL TO EXPLORE" 墨色 0.4 alpha = 2.4）都是**内联样式里的一个数字**，
 * 改的时候凭手感调成"我这块屏上够了"就完了。
 *
 * Lab 的背景是走廊的纸白（墙、地、天花都在 #ece7dd..#f4f0e8 之间），
 * 所以这里以 `CORRIDOR_PAPER` 为基准算对比度。
 */

/** 走廊纸白 —— 覆盖层文案的实际背景（取最亮的那面墙，最坏情况） */
export const CORRIDOR_PAPER = '#f4f0e8'

/**
 * 入口页的米色底（`app/page.tsx` 的 `background: '#f5f0e8'`）。
 *
 * 与 `CORRIDOR_PAPER` 只差一点，但对比度门禁必须按各自的背景算——用错背景
 * 得到的是一个看起来很精确的错数字。入口页的文案色目前不在 `OVERLAY_COLORS`
 * 里（还是散在 `ClassicPanel` 与 `page.tsx` 的内联样式里），门禁用棘轮登记着，
 * 见 `__tests__/labContrast.test.ts` 的 `KNOWN_LOW_CONTRAST`。
 */
export const ENTRY_PAPER = '#f5f0e8'

export const OVERLAY_COLORS = {
  /**
   * 走廊底部的操作提示（"滚动" / "上下滑动"）。
   *
   * 原先是 `rgba(42,31,14,0.4)`，压到纸白上是 rgb(161,154,142)，
   * 对比度 2.4。这是小字（10px），按正文要求 4.5。
   */
  hint: 'rgba(42,31,14,0.72)',

  /**
   * "← 退出 Lab"。
   *
   * 原先是 `rgba(200,169,110,0.6)`——金色在纸白上本来就浅，再乘 0.6 之后
   * 对比度只有 1.9，实机上基本看不见。改成不透明的深金：保住"这是个金色的
   * 品牌口子"，同时过 4.5。
   */
  exitLab: '#7a5d20',

  /**
   * 覆盖层里的**次要说明文字**（教程卡片的操作说明、兜底页的正文、
   * 鸭子对话框的提示）。
   *
   * 这些位置原先是 `rgba(42,31,14,0.5)` / `0.55` / `0.6`，压到纸白上分别是
   * 3.11 / 3.58 / 4.14——三个都过得了大字门槛 3，都过不了正文门槛 4.5，而它们
   * 全是 9–12px 的小字。第一版门禁一刀切用 3，所以一直是绿的。
   *
   * 0.66 是**刚好过线**的那一档（4.97）：再淡就不达标，再深就失去"次要文字"
   * 的层次感。改这个值之前先跑 `labContrast.test.ts`。
   */
  mutedText: 'rgba(42,31,14,0.66)',
} as const

/**
 * 入口页的文案色（背景是 `ENTRY_PAPER`）。
 *
 * 与 Lab 覆盖层分开：背景不同，同一个颜色在两处的对比度不一样，混用会算错。
 * 这一组以前散在 `ClassicPanel` 与 `app/page.tsx` 的内联样式里，而第一版门禁
 * 只认 `rgba()`、不认 `#hex`，所以四处金色（1.59 / 1.98 / 1.98 / 3.08）
 * 一直没被发现。
 */
export const ENTRY_COLORS = {
  /**
   * 金色强调文字（eyebrow、`ENTER →`）。
   *
   * 原先是 `#c8a96e`（1.98）与 `rgba(200,169,110,0.7)`（1.59）——金色在米底上
   * 本来就浅，再乘 alpha 就基本看不见了。`#846830` 是保住"这是金色"的色相
   * 前提下最浅的达标值（4.62）。
   */
  gold: '#846830',
  /** 方向标签的暖灰棕。原先 `#9c8570`（3.08）→ `#7d6857`（4.64） */
  tag: '#7d6857',
} as const
